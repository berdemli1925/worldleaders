// One-off admin script: creates the `countries` and `votes` tables in Supabase
// Postgres and seeds `countries` with the full ISO 3166-1 list.
//
// Usage:
//   DATABASE_URL="postgresql://postgres:...@db.xxxx.supabase.co:5432/postgres" node scripts/setup-database.mjs
//
// This is a schema/admin task, not something the running app ever needs to
// do — it uses a direct Postgres connection (not the Supabase JS client),
// and DATABASE_URL is intentionally NOT read from .env.local: it's only
// meant to be supplied transiently on the command line for this one run.

import pg from "pg";
import countries from "world-countries" ;

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error("Set DATABASE_URL to your Supabase Postgres connection string first.");
  process.exit(1);
}

const client = new pg.Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

async function main() {
  await client.connect();

  await client.query(`
    create table if not exists countries (
      iso_code text primary key,
      name text not null,
      continent text not null
    );
  `);

  await client.query(`
    create table if not exists votes (
      id bigint generated by default as identity primary key,
      country_iso_code text not null references countries (iso_code),
      voter_ip inet not null,
      created_at timestamptz not null default now()
    );
  `);

  // Added after the initial table creation: "one voter" is IP + browser
  // fingerprint together (see /api/votes), so the daily-vote lookup needs
  // this column. Nullable because it's backfilled onto a table that may
  // already have rows from before this column existed.
  await client.query(`alter table votes add column if not exists fingerprint text;`);

  await client.query(`create index if not exists votes_country_iso_code_idx on votes (country_iso_code);`);
  await client.query(`create index if not exists votes_created_at_idx on votes (created_at);`);
  // Matches the (voter_ip, fingerprint, created_at) lookup in findTodaysVote().
  await client.query(
    `create index if not exists votes_voter_ip_fingerprint_created_at_idx on votes (voter_ip, fingerprint, created_at);`,
  );

  // Lock both tables down by default (Supabase exposes every public-schema
  // table over its REST API). `countries` is harmless reference data, so we
  // open it up for public reads. `votes` gets no policies at all for now —
  // it holds voter IPs, and inserts must go through a rate-limited server
  // route (built in a later step) using the service_role key, which bypasses
  // RLS entirely and doesn't need a policy here.
  await client.query(`alter table countries enable row level security;`);
  await client.query(`alter table votes enable row level security;`);
  await client.query(`
    drop policy if exists "Public can read countries" on countries;
    create policy "Public can read countries" on countries for select using (true);
  `);

  const rows = countries.map((c) => [c.cca2, c.name.common, c.region]);

  await client.query("begin");
  try {
    for (const [isoCode, name, continent] of rows) {
      await client.query(
        `insert into countries (iso_code, name, continent) values ($1, $2, $3)
         on conflict (iso_code) do update set name = excluded.name, continent = excluded.continent;`,
        [isoCode, name, continent],
      );
    }
    await client.query("commit");
  } catch (err) {
    await client.query("rollback");
    throw err;
  }

  const { rows: countRows } = await client.query("select count(*)::int as count from countries;");
  console.log(`Inserted/updated ${rows.length} countries. Table now has ${countRows[0].count} rows.`);

  await client.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
