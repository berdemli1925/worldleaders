// One-off admin script: sets up the throne/leadership system — free "test
// mode" claims, no payment provider wired up yet. See proje-spesifikasyonu.md
// section 5 and this session's chat for the exact rules (some of which
// override the spec doc — see the plan/commit message).
//
// Usage:
//   DATABASE_URL="postgresql://postgres:...@db.xxxx.supabase.co:5432/postgres" node scripts/setup-throne-system.mjs
//
// Same DATABASE_URL-on-the-command-line-only pattern as the other two setup
// scripts. Safe to re-run: everything here is create-or-replace / if-not-
// exists / on-conflict / unschedule-then-reschedule.

import pg from "pg";

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error("Set DATABASE_URL to your Supabase Postgres connection string first.");
  process.exit(1);
}

const client = new pg.Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

async function main() {
  await client.connect();

  // pg_cron may already be enabled from scripts/setup-monthly-archive.mjs —
  // this is a harmless no-op in that case. Same "don't abort on permission
  // failure" handling as that script.
  try {
    await client.query(`create extension if not exists pg_cron;`);
  } catch (err) {
    console.warn(
      "Couldn't enable pg_cron automatically. Enable it manually: Supabase " +
        "dashboard -> Database -> Extensions -> pg_cron, then re-run this " +
        `script.\nReason: ${err instanceof Error ? err.message : err}`,
    );
  }

  // throne_claims first — thrones.current_claim_id references it.
  await client.query(`
    create table if not exists throne_claims (
      id bigint generated by default as identity primary key,
      country_iso_code text not null references countries (iso_code),
      x_handle text not null,
      amount_paid numeric(10,2) not null,
      post_snapshot jsonb not null,
      post_text text,
      post_author_name text,
      post_author_avatar_url text,
      post_image_url text,
      post_created_at timestamptz,
      claimer_ip inet,
      created_at timestamptz not null default now()
    );
  `);
  await client.query(
    `create index if not exists throne_claims_country_handle_idx on throne_claims (country_iso_code, x_handle);`,
  );

  await client.query(`
    create table if not exists thrones (
      country_iso_code text primary key references countries (iso_code),
      base_price numeric(10,2) not null default 1.50,
      current_value numeric(10,2),
      current_claim_id bigint references throne_claims (id),
      cycle_start timestamptz,
      cycle_end timestamptz,
      updated_at timestamptz not null default now()
    );
  `);

  // Seed one row per country so every country has a base_price from day
  // one, not just ones that have been claimed. Real prices come from the
  // refresh_throne_base_prices() call at the end of this script.
  await client.query(`
    insert into thrones (country_iso_code, base_price)
    select iso_code, 1.50 from countries
    on conflict (country_iso_code) do nothing;
  `);

  // Both tables carry voter IP / raw post content — no public policies.
  // Everything the client needs is exposed only through the two views below
  // (granted select), and writes only ever happen through claim_throne(),
  // called with the service-role key from src/app/api/throne/claim/route.ts.
  await client.query(`alter table thrones enable row level security;`);
  await client.query(`alter table throne_claims enable row level security;`);

  // Vacant-if-expired, computed live — correctness never depends on the
  // sweep cron having run recently.
  await client.query(`
    create or replace view thrones_live as
    select
      country_iso_code,
      base_price,
      case when cycle_end is not null and cycle_end > now() then current_value end as current_value,
      case when cycle_end is not null and cycle_end > now() then current_claim_id end as current_claim_id,
      case when cycle_end is not null and cycle_end > now() then cycle_start end as cycle_start,
      case when cycle_end is not null and cycle_end > now() then cycle_end end as cycle_end
    from thrones;
  `);

  await client.query(`
    create or replace view thrones_with_leader as
    select
      tl.country_iso_code,
      tl.base_price,
      tl.current_value,
      tl.cycle_start,
      tl.cycle_end,
      tc.id as current_claim_id,
      tc.x_handle,
      tc.amount_paid,
      tc.post_text,
      tc.post_author_name,
      tc.post_author_avatar_url,
      tc.post_image_url,
      tc.post_created_at,
      tc.created_at as claimed_at
    from thrones_live tl
    left join throne_claims tc on tc.id = tl.current_claim_id;
  `);

  // Public-safe view of claim history for the "past leaders" badges —
  // excludes claimer_ip and the raw post_snapshot jsonb (neither needed for
  // display; the IP in particular shouldn't be world-readable, same
  // reasoning as why `votes` itself has no public select policy).
  await client.query(`
    create or replace view throne_claims_public as
    select
      id, country_iso_code, x_handle, amount_paid,
      post_text, post_author_name, post_author_avatar_url, post_image_url, post_created_at,
      created_at
    from throne_claims;
  `);

  await client.query(
    `grant select on thrones_live, thrones_with_leader, throne_claims_public to anon, authenticated;`,
  );

  // All claim logic, atomically, under a row lock — see the worked example
  // below for how the credit math behaves across a claim -> outbid ->
  // reclaim sequence.
  //
  // Example (Italy, base $1.50):
  //   A claims for $1.50 (vacant)                -> credit(A)=0,   pays $1.50, credit(A) becomes $1.50
  //   B outbids, min is $1.50+2=$3.50, pays $3.50 -> credit(B)=0,   pays $3.50, credit(B) becomes $3.50
  //   A reclaims, min is $3.50+2=$5.50            -> credit(A)=$1.50 applied, pays net $4.00
  // Credit is always "how much of this user's past spend in the *current,
  // unexpired* cycle hasn't been consumed yet" — computed from
  // throne_claims, not stored anywhere, so it resets automatically the
  // moment a cycle lapses and cycle_start moves forward on the next claim.
  await client.query(`
    create or replace function claim_throne(
      p_country text,
      p_x_handle text,
      p_offered numeric,
      p_post_snapshot jsonb,
      p_post_text text,
      p_post_author_name text,
      p_post_author_avatar_url text,
      p_post_image_url text,
      p_post_created_at timestamptz,
      p_claimer_ip inet default null
    ) returns bigint
    language plpgsql
    as $$
    declare
      row thrones%rowtype;
      is_vacant boolean;
      required_min numeric(10,2);
      credit numeric(10,2) := 0;
      credit_applied numeric(10,2);
      net_paid numeric(10,2);
      new_cycle_start timestamptz;
      new_cycle_end timestamptz;
      new_claim_id bigint;
    begin
      select * into row from thrones where country_iso_code = p_country for update;
      if not found then
        raise exception 'Unknown country: %', p_country;
      end if;

      is_vacant := row.current_claim_id is null or row.cycle_end is null or row.cycle_end <= now();

      if is_vacant then
        required_min := row.base_price;
        new_cycle_start := now();
        new_cycle_end := now() + interval '7 days';
        credit := 0;
      else
        required_min := row.current_value + 2;
        new_cycle_start := row.cycle_start;
        new_cycle_end := row.cycle_end;

        select coalesce(sum(amount_paid), 0) into credit
        from throne_claims
        where country_iso_code = p_country
          and x_handle = p_x_handle
          and created_at >= row.cycle_start;
      end if;

      if p_offered < required_min then
        raise exception 'Offer of % is below the required minimum of % for %', p_offered, required_min, p_country;
      end if;

      credit_applied := least(credit, p_offered);
      net_paid := p_offered - credit_applied;

      insert into throne_claims (
        country_iso_code, x_handle, amount_paid, post_snapshot,
        post_text, post_author_name, post_author_avatar_url, post_image_url, post_created_at,
        claimer_ip
      ) values (
        p_country, p_x_handle, net_paid, p_post_snapshot,
        p_post_text, p_post_author_name, p_post_author_avatar_url, p_post_image_url, p_post_created_at,
        p_claimer_ip
      ) returning id into new_claim_id;

      update thrones
      set current_value = p_offered,
          current_claim_id = new_claim_id,
          cycle_start = new_cycle_start,
          cycle_end = new_cycle_end,
          updated_at = now()
      where country_iso_code = p_country;

      return new_claim_id;
    end;
    $$;
  `);

  // Hourly: recompute every country's base price from its monthly voting
  // rank ($3 top 10 / $2.50 top 30 / $2 top 70 / $1.50 rest). During the
  // first 24h of a UTC month, ranks by *last* month's votes instead (the
  // "ay başı istisnası") — computed directly from `votes`, not from the
  // month-scoped `leaderboard` view, so it's correct in both cases without
  // depending on last month's data still being "current" anywhere.
  await client.query(`
    create or replace function refresh_throne_base_prices() returns void
    language plpgsql
    as $$
    declare
      month_start timestamptz := date_trunc('month', now() at time zone 'utc');
      in_grace boolean := (now() at time zone 'utc') < (month_start + interval '24 hours');
    begin
      with ranked as (
        select
          c.iso_code,
          row_number() over (
            order by
              case when in_grace then coalesce(prev.vote_count, 0) else coalesce(cur.vote_count, 0) end desc,
              c.name asc
          ) as rnk
        from countries c
        left join lateral (
          select count(*)::int as vote_count from votes v
          where v.country_iso_code = c.iso_code
            and v.created_at >= month_start
            and v.created_at < month_start + interval '1 month'
        ) cur on true
        left join lateral (
          select count(*)::int as vote_count from votes v
          where v.country_iso_code = c.iso_code
            and v.created_at >= month_start - interval '1 month'
            and v.created_at < month_start
        ) prev on true
      )
      update thrones t
      set base_price = case
          when ranked.rnk <= 10 then 3.00
          when ranked.rnk <= 30 then 2.50
          when ranked.rnk <= 70 then 2.00
          else 1.50
        end,
        updated_at = now()
      from ranked
      where ranked.iso_code = t.country_iso_code;
    end;
    $$;
  `);

  // Every 15 min: physically vacate rows whose cycle has ended. Pure
  // eventual-consistency cleanup — thrones_live already reads these as
  // vacant instantly, this just keeps the stored rows from drifting stale
  // indefinitely between claims.
  await client.query(`
    create or replace function sweep_expired_thrones() returns void
    language sql
    as $$
      update thrones
      set current_value = null, current_claim_id = null, cycle_start = null, cycle_end = null, updated_at = now()
      where cycle_end is not null and cycle_end <= now();
    $$;
  `);

  try {
    await client.query(`
      do $$
      begin
        if exists (select 1 from cron.job where jobname = 'worldleaders-hourly-prices') then
          perform cron.unschedule('worldleaders-hourly-prices');
        end if;
        if exists (select 1 from cron.job where jobname = 'worldleaders-throne-sweep') then
          perform cron.unschedule('worldleaders-throne-sweep');
        end if;
      end $$;
    `);
    await client.query(`
      select cron.schedule('worldleaders-hourly-prices', '0 * * * *', $$select public.refresh_throne_base_prices();$$);
    `);
    await client.query(`
      select cron.schedule('worldleaders-throne-sweep', '*/15 * * * *', $$select public.sweep_expired_thrones();$$);
    `);
    console.log("Scheduled hourly base-price refresh and 15-minute expiry sweep.");
  } catch (err) {
    console.warn(
      "Couldn't schedule the pg_cron jobs (pg_cron likely isn't enabled — " +
        `see the warning above, if any). Re-run this script once it is.\nReason: ${
          err instanceof Error ? err.message : err
        }`,
    );
  }

  // Populate real base prices immediately rather than waiting for the top
  // of the hour.
  await client.query(`select refresh_throne_base_prices();`);

  const { rows: jobs } = await client.query(`select jobname, schedule, active from cron.job;`).catch(() => ({
    rows: [],
  }));
  console.log("Current pg_cron jobs:", jobs);

  const { rows: sample } = await client.query(
    `select country_iso_code, base_price from thrones order by base_price desc, country_iso_code limit 5;`,
  );
  console.log("Sample base prices:", sample);

  await client.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
