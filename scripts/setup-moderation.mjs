// One-off admin script: moderation system + expanded claim content fields.
// Must be run before payment goes live (see proje-spesifikasyonu.md section
// 5 and this session's chat). Builds on the throne system from
// scripts/setup-throne-system.mjs — this only extends it.
//
// Usage:
//   DATABASE_URL="postgresql://postgres:...@db.xxxx.supabase.co:5432/postgres" node scripts/setup-moderation.mjs
//
// Same DATABASE_URL-on-the-command-line-only pattern as the other setup
// scripts. Safe to re-run: everything here is add-column-if-not-exists /
// create-or-replace / if-not-exists / on-conflict.

import pg from "pg";

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error("Set DATABASE_URL to your Supabase Postgres connection string first.");
  process.exit(1);
}

const client = new pg.Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

async function main() {
  await client.connect();

  // --- Expanded claim content fields + moderation bookkeeping -----------
  await client.query(`
    alter table throne_claims
      add column if not exists brand_title text,
      add column if not exists description text,
      add column if not exists link_url text,
      add column if not exists logo_url text,
      add column if not exists removed_at timestamptz,
      add column if not exists removed_reason text;
  `);

  // --- New tables ---------------------------------------------------------
  await client.query(`
    create table if not exists blocked_handles (
      x_handle text primary key,
      reason text,
      blocked_at timestamptz not null default now()
    );
  `);

  await client.query(`
    create table if not exists moderation_reports (
      id bigint generated by default as identity primary key,
      throne_claim_id bigint not null references throne_claims (id),
      reason text not null,
      details text,
      reporter_ip inet,
      created_at timestamptz not null default now(),
      resolved_at timestamptz,
      resolved_note text
    );
  `);
  await client.query(
    `create index if not exists moderation_reports_claim_idx on moderation_reports (throne_claim_id);`,
  );

  await client.query(`
    create table if not exists site_settings (
      key text primary key,
      value jsonb not null,
      updated_at timestamptz not null default now()
    );
  `);
  await client.query(`
    insert into site_settings (key, value) values ('leadership_hidden', 'false'::jsonb)
    on conflict (key) do nothing;
  `);

  // No public policies on any of these — same posture as `votes` /
  // `throne_claims`. All reads/writes go through supabaseAdmin (server-only)
  // or the public views below.
  await client.query(`alter table blocked_handles enable row level security;`);
  await client.query(`alter table moderation_reports enable row level security;`);
  await client.query(`alter table site_settings enable row level security;`);

  // --- thrones_live: kill-switch aware ------------------------------------
  // When leadership_hidden is true, every country reads as vacant —
  // thrones_with_leader inherits this automatically since it's built on top
  // of this view. throne_claims_public (history badges) is deliberately
  // left untouched: it carries no live content (just "@handle · $amount"),
  // only the currently-displayed leader is the actual moderation liability.
  await client.query(`
    create or replace view thrones_live as
    select
      t.country_iso_code,
      t.base_price,
      case when t.cycle_end is not null and t.cycle_end > now() and not hidden.flag then t.current_value end as current_value,
      case when t.cycle_end is not null and t.cycle_end > now() and not hidden.flag then t.current_claim_id end as current_claim_id,
      case when t.cycle_end is not null and t.cycle_end > now() and not hidden.flag then t.cycle_start end as cycle_start,
      case when t.cycle_end is not null and t.cycle_end > now() and not hidden.flag then t.cycle_end end as cycle_end
    from thrones t,
      lateral (
        select coalesce(
          (select (value #>> '{}')::boolean from site_settings where key = 'leadership_hidden'),
          false
        ) as flag
      ) hidden;
  `);

  // thrones_with_leader now also carries the new content fields. Postgres's
  // create-or-replace-view only allows *appending* columns at the end — it
  // errors if an existing column's name/position shifts — so the new
  // columns go after claimed_at, not interleaved with the original ones.
  await client.query(`
    create or replace view thrones_with_leader as
    select
      tl.country_iso_code,
      tl.base_price,
      tl.current_value,
      tl.cycle_start,
      tl.cycle_end,
      tc.id as current_claim_id,
      tc.x_handle,
      tc.amount_paid,
      tc.post_text,
      tc.post_author_name,
      tc.post_author_avatar_url,
      tc.post_image_url,
      tc.post_created_at,
      tc.created_at as claimed_at,
      tc.brand_title,
      tc.description,
      tc.link_url,
      tc.logo_url
    from thrones_live tl
    left join throne_claims tc on tc.id = tl.current_claim_id;
  `);

  // throne_claims_public also gains the new content columns (appended after
  // created_at for the same reason as above), for symmetry with the live
  // view — history badges may want brand_title later even though the
  // current UI only uses handle + amount.
  await client.query(`
    create or replace view throne_claims_public as
    select
      id, country_iso_code, x_handle, amount_paid,
      post_text, post_author_name, post_author_avatar_url, post_image_url, post_created_at,
      created_at,
      brand_title, description, link_url, logo_url
    from throne_claims;
  `);

  await client.query(`
    grant select on thrones_live, thrones_with_leader, throne_claims_public to anon, authenticated;
  `);

  // --- claim_throne(): extended with content fields + two new guards -----
  // Same core logic as before (vacancy check, +$2 minimum, credit math,
  // cycle timing) — only the new blocked-handle and kill-switch checks, and
  // the four new content params, are additions.
  //
  // Postgres resolves functions by name + argument types, so adding params
  // makes `create or replace` create a *second*, separately-overloaded
  // claim_throne instead of truly replacing the old one — drop the old
  // exact signature first so there's only ever one.
  await client.query(`
    drop function if exists claim_throne(text, text, numeric, jsonb, text, text, text, text, timestamptz, inet);
  `);
  await client.query(`
    create or replace function claim_throne(
      p_country text,
      p_x_handle text,
      p_offered numeric,
      p_post_snapshot jsonb,
      p_post_text text,
      p_post_author_name text,
      p_post_author_avatar_url text,
      p_post_image_url text,
      p_post_created_at timestamptz,
      p_claimer_ip inet default null,
      p_brand_title text default null,
      p_description text default null,
      p_link_url text default null,
      p_logo_url text default null
    ) returns bigint
    language plpgsql
    as $$
    declare
      row thrones%rowtype;
      is_vacant boolean;
      required_min numeric(10,2);
      credit numeric(10,2) := 0;
      credit_applied numeric(10,2);
      net_paid numeric(10,2);
      new_cycle_start timestamptz;
      new_cycle_end timestamptz;
      new_claim_id bigint;
      leadership_hidden boolean;
    begin
      if exists (select 1 from blocked_handles where x_handle = p_x_handle) then
        raise exception 'This X account is blocked from claiming a throne.';
      end if;

      select coalesce((value #>> '{}')::boolean, false) into leadership_hidden
      from site_settings where key = 'leadership_hidden';
      if leadership_hidden then
        raise exception 'Leadership claims are temporarily paused.';
      end if;

      select * into row from thrones where country_iso_code = p_country for update;
      if not found then
        raise exception 'Unknown country: %', p_country;
      end if;

      is_vacant := row.current_claim_id is null or row.cycle_end is null or row.cycle_end <= now();

      if is_vacant then
        required_min := row.base_price;
        new_cycle_start := now();
        new_cycle_end := now() + interval '7 days';
        credit := 0;
      else
        required_min := row.current_value + 2;
        new_cycle_start := row.cycle_start;
        new_cycle_end := row.cycle_end;

        select coalesce(sum(amount_paid), 0) into credit
        from throne_claims
        where country_iso_code = p_country
          and x_handle = p_x_handle
          and created_at >= row.cycle_start;
      end if;

      if p_offered < required_min then
        raise exception 'Offer of % is below the required minimum of % for %', p_offered, required_min, p_country;
      end if;

      credit_applied := least(credit, p_offered);
      net_paid := p_offered - credit_applied;

      insert into throne_claims (
        country_iso_code, x_handle, amount_paid, post_snapshot,
        post_text, post_author_name, post_author_avatar_url, post_image_url, post_created_at,
        claimer_ip, brand_title, description, link_url, logo_url
      ) values (
        p_country, p_x_handle, net_paid, p_post_snapshot,
        p_post_text, p_post_author_name, p_post_author_avatar_url, p_post_image_url, p_post_created_at,
        p_claimer_ip, p_brand_title, p_description, p_link_url, p_logo_url
      ) returning id into new_claim_id;

      update thrones
      set current_value = p_offered,
          current_claim_id = new_claim_id,
          cycle_start = new_cycle_start,
          cycle_end = new_cycle_end,
          updated_at = now()
      where country_iso_code = p_country;

      return new_claim_id;
    end;
    $$;
  `);

  // --- remove_claim(): content takedown (admin button + auto change-check)
  await client.query(`
    create or replace function remove_claim(p_claim_id bigint, p_reason text) returns void
    language plpgsql
    as $$
    begin
      update throne_claims
      set removed_at = now(), removed_reason = p_reason
      where id = p_claim_id and removed_at is null;

      update thrones
      set current_value = null, current_claim_id = null, cycle_start = null, cycle_end = null, updated_at = now()
      where current_claim_id = p_claim_id;
    end;
    $$;
  `);

  // --- reset_throne(): admin's blunt "reset this country" action ---------
  await client.query(`
    create or replace function reset_throne(p_country text) returns void
    language sql
    as $$
      update thrones
      set current_value = null, current_claim_id = null, cycle_start = null, cycle_end = null, updated_at = now()
      where country_iso_code = p_country;
    $$;
  `);

  console.log("Moderation system set up: blocked_handles, moderation_reports, site_settings, updated views/functions.");
  console.log("Remember to set ADMIN_PASSWORD and CRON_SECRET env vars before using /admin or the cron route.");

  await client.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
