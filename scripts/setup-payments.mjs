// One-off admin script: provider-agnostic payment layer. Adds a `payments`
// table tracking every claim attempt's payment lifecycle (pending →
// completed/failed) and finalize_payment(), which wraps the existing
// claim_throne() so all its business rules (vacancy, +$2 minimum, credit
// math, blocked handles, kill switch) keep being the single source of
// truth — this function only adds payment bookkeeping + idempotency
// around it, never duplicates its logic.
//
// Usage:
//   DATABASE_URL="postgresql://postgres:...@db.xxxx.supabase.co:5432/postgres" node scripts/setup-payments.mjs
//
// Same DATABASE_URL-on-the-command-line-only pattern as the other setup
// scripts. Safe to re-run.

import pg from "pg";

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  console.error("Set DATABASE_URL to your Supabase Postgres connection string first.");
  process.exit(1);
}

const client = new pg.Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

async function main() {
  await client.connect();

  await client.query(`
    create table if not exists payments (
      id bigint generated by default as identity primary key,
      country_iso_code text not null references countries (iso_code),
      x_handle text not null,
      amount numeric(10,2) not null,
      credit_applied numeric(10,2),
      net_amount numeric(10,2),
      provider text not null default 'mock',
      provider_reference text,
      status text not null default 'pending' check (status in ('pending', 'completed', 'failed')),
      failure_reason text,
      throne_claim_id bigint references throne_claims (id),
      post_snapshot jsonb not null,
      post_text text,
      post_author_name text,
      post_author_avatar_url text,
      post_image_url text,
      post_created_at timestamptz,
      brand_title text,
      description text,
      link_url text,
      logo_url text,
      claimer_ip inet,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    );
  `);
  await client.query(`create index if not exists payments_provider_reference_idx on payments (provider_reference);`);
  await client.query(`create index if not exists payments_country_idx on payments (country_iso_code, created_at desc);`);

  // No public policies — same posture as throne_claims/votes. Only
  // supabaseAdmin (service role, from the claim route and the admin
  // panel) ever reads or writes this table.
  await client.query(`alter table payments enable row level security;`);

  // The concurrency/idempotency guarantee lives entirely in this function:
  // - `for update` on the payment row makes a retried webhook (or a
  //   double-fired mock "immediate result") a safe no-op via the
  //   status != 'pending' check.
  // - claim_throne()'s own row lock on `thrones` is what makes "two
  //   people pay for the same country at once" resolve to exactly one
  //   winner — the loser's call into claim_throne() raises (offer below
  //   the now-current minimum), which this function turns into
  //   status = 'failed' instead of granting anything.
  await client.query(`
    create or replace function finalize_payment(p_payment_id bigint, p_provider_success boolean default true)
    returns jsonb
    language plpgsql
    as $$
    declare
      pay payments%rowtype;
      new_claim_id bigint;
    begin
      select * into pay from payments where id = p_payment_id for update;
      if not found then
        raise exception 'Unknown payment: %', p_payment_id;
      end if;

      if pay.status != 'pending' then
        return jsonb_build_object('status', pay.status, 'alreadyProcessed', true);
      end if;

      if not p_provider_success then
        update payments
        set status = 'failed', failure_reason = 'Declined by payment provider.', updated_at = now()
        where id = p_payment_id;
        return jsonb_build_object('status', 'failed', 'reason', 'Declined by payment provider.');
      end if;

      begin
        new_claim_id := claim_throne(
          pay.country_iso_code, pay.x_handle, pay.amount, pay.post_snapshot,
          pay.post_text, pay.post_author_name, pay.post_author_avatar_url, pay.post_image_url, pay.post_created_at,
          pay.claimer_ip, pay.brand_title, pay.description, pay.link_url, pay.logo_url
        );

        update payments
        set status = 'completed',
            throne_claim_id = new_claim_id,
            net_amount = (select amount_paid from throne_claims where id = new_claim_id),
            credit_applied = pay.amount - (select amount_paid from throne_claims where id = new_claim_id),
            updated_at = now()
        where id = p_payment_id;

        return jsonb_build_object('status', 'completed', 'claimId', new_claim_id);
      exception when others then
        update payments
        set status = 'failed', failure_reason = SQLERRM, updated_at = now()
        where id = p_payment_id;
        return jsonb_build_object('status', 'failed', 'reason', SQLERRM);
      end;
    end;
    $$;
  `);

  console.log("Payments table + finalize_payment() set up.");
  console.log("Remember to set PAYMENT_PROVIDER=mock (default) in .env.local — no other setup needed for test mode.");

  await client.end();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
